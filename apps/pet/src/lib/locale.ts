/** 模板替换：fmt('离开了 {h} 小时', { h: 3 }) */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replaceAll(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}
